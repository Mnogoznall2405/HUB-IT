#!/usr/bin/env python3
"""Issue #89 — build-time генерация emoji sprite-атласа по модели Telegram Desktop.

Читает набор эмодзи, который реально рендерит emoji-picker-react
(node_modules/emoji-picker-react/src/data/emojis.json), в том порядке категорий,
в котором они показываются в панели чата, и раскладывает apple/64 PNG по листам
32x16 ячеек (512 эмодзи на лист, 2048x1024 px) — как sheets в tdesktop.

Выход (коммитится в репозиторий, перегенерация — только при смене
emoji-datasource-apple или emoji-picker-react):

  public/emoji-atlas/sheet-<n>.<hash>.png  — листы спрайтов (lossless PNG: пиксели
                                             идентичны текущему рендеру, decode
                                             быстрее WebP — замерено в issue #89).
                                             <hash> — первые 10 hex sha256 содержимого:
                                             при смене данных меняется имя файла, поэтому
                                             закэшированный старый лист никогда не встретит
                                             новые позиции CSS (cache-invalidation без
                                             зависимости от max-age статики).
  src/lib/chat/generated/emojiSpriteData.js — упорядоченный список unified +
                                             параметры раскладки (индекс вычислим:
                                             позиция в списке = ячейка) + имена листов
  src/lib/chat/generated/emojiSprites.css   — per-emoji правила background-position
                                             (шаблон с плейсхолдером базы, см.
                                             emojiSpriteAtlas.js)

Запуск из каталога frontend:  python scripts/generate-emoji-atlas.py
"""

import hashlib
import io
import json
import sys
from pathlib import Path

from PIL import Image

FRONTEND_DIR = Path(__file__).resolve().parent.parent
PICKER_DATA = FRONTEND_DIR / "node_modules" / "emoji-picker-react" / "src" / "data" / "emojis.json"
APPLE_IMG_DIR = FRONTEND_DIR / "node_modules" / "emoji-datasource-apple" / "img" / "apple" / "64"
OUT_SHEETS_DIR = FRONTEND_DIR / "public" / "emoji-atlas"
OUT_GENERATED_DIR = FRONTEND_DIR / "src" / "lib" / "chat" / "generated"

CELL_PX = 64
COLS = 32
ROWS_PER_SHEET = 16
CELLS_PER_SHEET = COLS * ROWS_PER_SHEET  # 512, как в Telegram Desktop

# Порядок категорий как в ChatEmojiPanel (suggested — динамический, использует
# уже проиндексированные unified, поэтому отдельно не нужен).
CATEGORY_ORDER = [
    "smileys_people",
    "animals_nature",
    "food_drink",
    "travel_places",
    "activities",
    "objects",
    "symbols",
    "flags",
]

# Геометрия фона на КНОПКЕ (итерация 2 — см. issue89-report.md):
# кнопка .epr-emoji — квадрат --epr-emoji-fullsize = size + 2*padding, без рамки.
# Кнопке задаём padding = --epr-emoji-padding, поэтому её content-box совпадает
# с content-box'ом <img> из img-варианта (img форсирован min/max-width/height в
# fullsize и flex-центрирован — симметричный padding на центровку не влияет,
# он лишь делает геометрию независимой от UA-отступов <button>). Позиции листа
# в координатах content-box: (-x*size, -y*size) — в точности как в проверенном
# img-варианте.
#
# Зачем background-clip:content-box (двухслойный фон): глифы apple почти заполняют
# ячейку 64px (поля всего 2px), а браузер даунскейлит лист широким фильтром —
# края СОСЕДНИХ ячеек размазываются на 1-2 css px в padding-кольцо кнопки
# (оранжевые штрихи между глифами, подтверждено попиксельно и в итерации 1, и в
# итерации 2). Клип content-box отрезает это кольцо. Нижний слой — прозрачный
# градиент с clip:padding-box: background-color красится по клипу НИЖНЕГО слоя,
# поэтому без него hover/focus-подсветка кнопки схлопнулась бы до content-box.
CSS_PREAMBLE = """/* GENERATED by scripts/generate-emoji-atlas.py — не редактировать вручную.
 * Sprite-атлас эмодзи (issue #89): индексированный эмодзи рисуется фоном КНОПКИ
 * picker'а (<img> внутри несёт прозрачный пиксель). Геометрия: padding кнопки ==
 * --epr-emoji-padding -> её content-box == content-box бывшего img; позиция листа
 * -cell*size в координатах content-box. Лист 2048px = 32 ячейки по 64px ->
 * background-size масштабирует лист так, что ячейка == --epr-emoji-size при любом
 * размере сетки. Верхний слой (лист) клипается content-box'ом — иначе даунскейл
 * размазывает края соседних ячеек в padding-кольцо (штрихи между глифами);
 * нижний прозрачный слой с clip:padding-box сохраняет hover/focus-подсветку
 * на всю кнопку. {base} заменяется рантаймом на import.meta.env.BASE_URL +
 * 'emoji-atlas/' (см. emojiSpriteAtlas.js).
 */
.chat-emoji-sprite-scope .epr-emoji{
padding:var(--epr-emoji-padding);
--epr-sprite-fill:linear-gradient(transparent,transparent);
background-repeat:no-repeat,no-repeat;
background-origin:content-box,padding-box;
background-clip:content-box,padding-box;
background-size:calc(var(--epr-emoji-size)*%d) auto,auto;
}
""" % COLS


def load_emoji_sequence() -> list[str]:
    data = json.loads(PICKER_DATA.read_text(encoding="utf-8"))
    available = {p.stem for p in APPLE_IMG_DIR.glob("*.png")}
    sequence: list[str] = []
    seen: set[str] = set()
    skipped: list[str] = []
    for category in CATEGORY_ORDER:
        for entry in data["emojis"].get(category, []):
            unified = str(entry["u"]).lower()
            if unified in seen:
                continue
            seen.add(unified)
            if unified not in available:
                skipped.append(unified)
                continue
            sequence.append(unified)
    return sequence, skipped


def sheet_file_name(sheet_index: int, png_bytes: bytes) -> str:
    digest = hashlib.sha256(png_bytes).hexdigest()[:10]
    return f"sheet-{sheet_index}.{digest}.png"


def build_sheets(sequence: list[str]) -> list[dict]:
    OUT_SHEETS_DIR.mkdir(parents=True, exist_ok=True)
    # Удаляем листы прошлой генерации (в т.ч. старые имена с другим хэшем):
    # каталог принадлежит генератору, stale-файлы не должны попадать в коммит.
    for stale in OUT_SHEETS_DIR.glob("sheet-*.png"):
        stale.unlink()
    sheets = []
    for sheet_index in range((len(sequence) + CELLS_PER_SHEET - 1) // CELLS_PER_SHEET):
        chunk = sequence[sheet_index * CELLS_PER_SHEET:(sheet_index + 1) * CELLS_PER_SHEET]
        rows = (len(chunk) + COLS - 1) // COLS
        image = Image.new("RGBA", (COLS * CELL_PX, rows * CELL_PX), (0, 0, 0, 0))
        for pos, unified in enumerate(chunk):
            cell = Image.open(APPLE_IMG_DIR / f"{unified}.png").convert("RGBA")
            image.paste(cell, ((pos % COLS) * CELL_PX, (pos // COLS) * CELL_PX))
        buffer = io.BytesIO()
        image.save(buffer, format="PNG", optimize=True)
        png_bytes = buffer.getvalue()
        name = sheet_file_name(sheet_index, png_bytes)
        out = OUT_SHEETS_DIR / name
        out.write_bytes(png_bytes)
        sheets.append({
            "index": sheet_index,
            "file": name,
            "cells": len(chunk),
            "rows": rows,
            "bytes": len(png_bytes),
        })
        print(f"{name}: {len(chunk)} cells, {rows} rows, {len(png_bytes)} bytes")
    return sheets


def write_sprite_data(sequence: list[str], sheets: list[dict]) -> None:
    OUT_GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    packed = " ".join(sequence)
    files = ", ".join(f"'{s['file']}'" for s in sheets)
    content = (
        "// GENERATED by scripts/generate-emoji-atlas.py — не редактировать вручную.\n"
        "// Упорядоченный список unified эмодзи sprite-атласа: позиция в списке =\n"
        "// ячейка атласа (sheet = idx // 512, x = idx % 32, y = (idx % 512) // 32).\n"
        "// EMOJI_SPRITE_SHEET_FILES — имена листов с content-hash (см. генератор).\n"
        f"export const EMOJI_SPRITE_COLS = {COLS};\n"
        f"export const EMOJI_SPRITE_CELLS_PER_SHEET = {CELLS_PER_SHEET};\n"
        f"export const EMOJI_SPRITE_SHEET_COUNT = {len(sheets)};\n"
        f"export const EMOJI_SPRITE_SHEET_FILES = [{files}];\n"
        f"export const EMOJI_SPRITE_ORDER =\n  '{packed}';\n"
    )
    # newline="\n": текстовый режим Windows иначе раздувает файл CR-мами,
    # а сгенерированный CSS встраивается в js-бандл как есть.
    (OUT_GENERATED_DIR / "emojiSpriteData.js").write_text(content, encoding="utf-8", newline="\n")
    print(f"emojiSpriteData.js: {len(sequence)} emojis, {len(content)} bytes")


def cell_axis_pos(cells_offset: int) -> str:
    # Позиция вдоль одной оси в координатах content-box кнопки: -cells*size.
    if cells_offset == 0:
        return "0px"
    return f"calc(var(--epr-emoji-size)*-{cells_offset})"


def write_sprite_css(sequence: list[str], sheets: list[dict]) -> None:
    lines = [CSS_PREAMBLE]
    for idx, unified in enumerate(sequence):
        sheet = idx // CELLS_PER_SHEET
        cell = idx % CELLS_PER_SHEET
        x = cell % COLS
        y = cell // COLS
        lines.append(
            '.chat-emoji-sprite-scope '
            f'.epr-emoji[data-unified="{unified}"]{{'
            f'background-image:url("{{base}}{sheets[sheet]["file"]}"),var(--epr-sprite-fill);'
            f'background-position:{cell_axis_pos(x)} {cell_axis_pos(y)},0px 0px;'
            '}\n'
        )
    content = "".join(lines)
    (OUT_GENERATED_DIR / "emojiSprites.css").write_text(content, encoding="utf-8", newline="\n")
    print(f"emojiSprites.css: {len(sequence)} rules, {len(content)} bytes")


def main() -> int:
    if not PICKER_DATA.is_file():
        print(f"error: нет данных picker'а: {PICKER_DATA} (нужен npm install)", file=sys.stderr)
        return 1
    if not APPLE_IMG_DIR.is_dir():
        print(f"error: нет apple images: {APPLE_IMG_DIR} (нужен npm install)", file=sys.stderr)
        return 1
    sequence, skipped = load_emoji_sequence()
    print(f"emojis indexed: {len(sequence)}, skipped (no apple png — native fallback как сегодня): {skipped}")
    sheets = build_sheets(sequence)
    write_sprite_data(sequence, sheets)
    write_sprite_css(sequence, sheets)
    total = sum(s["bytes"] for s in sheets)
    print(f"total sheet bytes: {total} ({total / 1048576:.2f} MiB) for {len(sequence)} emojis")
    return 0


if __name__ == "__main__":
    sys.exit(main())
